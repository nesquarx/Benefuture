"""Regenerate docs/THEOREM_INDEX.md: every theorem and lemma in Benefuture/, with its location,
docstring and statement head. Docstrings are the authors' summaries and are not reviewed here;
the reviewed claims are in README.md (Claims). Usage: python3 tools/theorem_index.py"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent


def theorems():
    for f in sorted((ROOT / "Benefuture").rglob("*.lean")):
        lines = f.read_text().split("\n")
        for i, line in enumerate(lines):
            m = re.match(r"(theorem|lemma)\s+(\S+)", line)
            if not m:
                continue
            doc, j = "", i - 1
            while j >= 0 and not lines[j].strip():
                j -= 1
            if j >= 0 and lines[j].strip().endswith("-/"):
                k = j
                while k >= 0 and "/-" not in lines[k]:
                    k -= 1
                doc = " ".join(x.strip() for x in lines[k:j + 1]).replace("/--", "").replace("/-", "").replace("-/", "")
            stmt, k = [], i
            while k < len(lines):
                stmt.append(lines[k].strip())
                if ":=" in lines[k]:
                    break
                k += 1
            yield (f.relative_to(ROOT).as_posix(), i + 1, m.group(2), re.sub(r"\s+", " ", doc).strip(),
                   re.sub(r"\s+", " ", " ".join(stmt).split(":=")[0]).strip())


def escape_hatches():
    """Report proof escape hatches (sorry, admit, custom axioms, native_decide) outside comments."""
    hits = []
    for f in sorted((ROOT / "Benefuture").rglob("*.lean")):
        for n, line in enumerate(f.read_text().split("\n"), 1):
            code = line.split("--")[0]
            if re.search(r"\bsorry\b|\badmit\b|^\s*axiom\s|native_decide", code):
                hits.append(f"`{f.relative_to(ROOT).as_posix()}:{n}`")
    return "Escape hatches (`sorry`, `admit`, custom `axiom`, `native_decide`): " + (", ".join(hits) if hits else "none found.")


def main():
    rows = list(theorems())
    out = ["# Theorem index", "",
           "Every theorem and lemma in `Benefuture/` (generated by `tools/theorem_index.py`; do not edit by hand).",
           "Descriptions are the docstrings as written and are **not reviewed**: some overstate what the statement",
           "proves. The reviewed claims, with their assumptions, are in [README.md](../README.md#claims).", "",
           f"{len(rows)} entries. {escape_hatches()}", ""]
    current = None
    for path, line, name, doc, stmt in rows:
        if path != current:
            out += ["", f"## {path}", ""]
            current = path
        desc = doc if doc else "(no docstring)"
        out.append(f"- [`{name}`](../{path}#L{line}): {desc}")
    (ROOT / "docs" / "THEOREM_INDEX.md").write_text("\n".join(out) + "\n")
    print(len(rows), "entries")


if __name__ == "__main__":
    main()
