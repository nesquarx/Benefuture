#!/usr/bin/env node
/**
 * build-graph.mjs — parse Bf_Pseudocode.txt and regenerate the interactive
 * concept-graph canvas (bf-concept-graph.canvas.tsx).
 *
 * Usage:
 *   node tools/bf-graph/build-graph.mjs            one-shot build
 *   node tools/bf-graph/build-graph.mjs --watch    rebuild on every pseudocode save
 *   flags: --src <path> --out <path>
 *
 * The canvas is written to this workspace's managed canvases directory so the
 * IDE picks it up automatically; --out overrides the destination.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseBfPseudocode } from "./parse.mjs";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const workspaceRoot = path.resolve(scriptDir, "..", "..");

const args = process.argv.slice(2);
const argValue = (flag) => {
  const i = args.indexOf(flag);
  return i >= 0 ? args[i + 1] : null;
};

const src = path.resolve(workspaceRoot, argValue("--src") ?? "Bf_Pseudocode.txt");
const slug = workspaceRoot.replace(/^\/+/, "").replace(/[\\/]/g, "-");
const defaultOut = path.join(
  os.homedir(),
  ".cursor",
  "projects",
  slug,
  "canvases",
  "bf-concept-graph.canvas.tsx"
);
const out = path.resolve(workspaceRoot, argValue("--out") ?? defaultOut);
const templatePath = path.join(scriptDir, "canvas-template.tsx");
const watch = args.includes("--watch");

async function build() {
  const text = fs.readFileSync(src, "utf8");
  const graph = parseBfPseudocode(text);
  const template = fs.readFileSync(templatePath, "utf8");

  const data = {
    source: path.basename(src),
    sourcePath: src,
    generatedAt: new Date().toISOString(),
    stats: {
      sections: graph.stats.sections,
      axioms: graph.nodes.filter((n) => n.axiom).length,
    },
    categories: graph.categories,
    nodes: graph.nodes,
    edges: graph.edges,
  };

  const block =
    "// __GENERATED_DATA_BEGIN__\n" +
    "// Auto-generated by tools/bf-graph/build-graph.mjs — do not edit by hand.\n" +
    `const GENERATED: GeneratedData = ${JSON.stringify(data, null, 1)};\n` +
    "// __GENERATED_DATA_END__";

  if (!template.includes("__GENERATED_DATA_BEGIN__")) {
    throw new Error("template is missing GENERATED markers");
  }
  const next = template.replace(
    /\/\/ __GENERATED_DATA_BEGIN__[\s\S]*?\/\/ __GENERATED_DATA_END__/,
    block
  );

  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, next);
  const readBack = fs.readFileSync(out, "utf8");
  if (readBack !== next) {
    console.error(
      `[bf-graph] WARNING: wrote ${out} (${next.length} chars) but read-back has ` +
        `${readBack.length} chars — another process may be managing this file.`
    );
  }
  if (watch) {
    // The IDE holds open canvases in memory and may restore its own version over
    // an external write; check persistence after a few seconds and say so.
    await new Promise((r) => setTimeout(r, 4000));
    const later = fs.readFileSync(out, "utf8");
    if (later !== next) {
      console.warn(
        "[bf-graph] note: the canvas file no longer matches this build — the IDE is " +
          "holding its own in-memory version. Close and reopen the canvas tab to see the update."
      );
    }
  }
  const rel = path.relative(workspaceRoot, out);
  console.log(
    `[bf-graph] ${new Date().toLocaleTimeString()}  ${graph.nodes.length} nodes · ` +
      `${graph.edges.length} edges · ${graph.categories.length} categories → ` +
      (rel.startsWith("..") ? out : rel)
  );
}

async function main() {
  await build();

  if (watch) {
    // Watch the containing directory (not the file) so atomic-save editors that
    // write-then-rename still trigger rebuilds. Fall back to stat polling when
    // fs.watch is unavailable (e.g. sandboxed environments with fd limits).
    const dir = path.dirname(src);
    const base = path.basename(src);
    let timer = null;
    let building = false;
    let pending = false;
    const rebuild = () => {
      clearTimeout(timer);
      timer = setTimeout(async () => {
        if (building) {
          pending = true;
          return;
        }
        building = true;
        try {
          await build();
        } catch (err) {
          console.error(`[bf-graph] rebuild failed: ${err.message}`);
        }
        building = false;
        if (pending) {
          pending = false;
          rebuild();
        }
      }, 150);
    };
    const startPolling = () => {
      console.warn("[bf-graph] falling back to polling (500ms interval).");
      fs.watchFile(src, { interval: 500 }, (curr, prev) => {
        if (curr.mtimeMs !== prev.mtimeMs) rebuild();
      });
    };
    try {
      const watcher = fs.watch(dir, (event, filename) => {
        if (filename && filename !== base) return;
        rebuild();
      });
      watcher.on("error", (err) => {
        console.warn(`[bf-graph] fs.watch failed: ${err.code ?? err.message}.`);
        try {
          watcher.close();
        } catch {}
        startPolling();
      });
    } catch (err) {
      console.warn(`[bf-graph] fs.watch unavailable: ${err.code ?? err.message}.`);
      startPolling();
    }
    console.log(`[bf-graph] watching ${src} — edit it and the canvas updates.`);
  }
}

main().catch((err) => {
  console.error(`[bf-graph] build failed: ${err.message}`);
  process.exitCode = 1;
});
