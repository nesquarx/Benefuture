def clean(x):
    if isinstance(x, float):
        return None if math.isnan(x) else round(x, 5)
    if isinstance(x, dict):
        return {k: clean(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [clean(v) for v in x]
    if isinstance(x, np.generic):
        return clean(x.item())
    return x


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "data/gold/identification_ceiling"))
    ap.add_argument("--reading")
    ap.add_argument("--render-only", action="store_true")
    ap.add_argument("--predictions-only", action="store_true")
    a = ap.parse_args()
    out_path = Path(a.out)
    if a.predictions_only:
        out_path.with_suffix(".md").write_text(report(), encoding="utf-8")
        return
    reading = Path(a.reading).read_text(encoding="utf-8") if a.reading else None
    if a.render_only:
        out = json.loads(out_path.with_suffix(".json").read_text(encoding="utf-8"))
    else:
        out = clean(run())
        out_path.with_suffix(".json").write_text(json.dumps(out, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    out_path.with_suffix(".md").write_text(report(out, reading), encoding="utf-8")
    for lv in LEVELS:
        print(f"{lv:12s} " + "  ".join(f"{lab} {c} {out['results'][lv][lab][c]['accuracy']:.3f}" for lab in LABELS for c in CLFS))
    for v in out["verdicts"]:
        print(v["id"], v["verdict"])


if __name__ == "__main__":
    main()
