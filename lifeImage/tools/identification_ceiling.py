#!/usr/bin/env python3
"""Where is the ceiling of blind identification? The same leave-one-out protocol at three levels of one population.

    python3 tools/identification_ceiling.py [--out data/gold/identification_ceiling] [--reading FILE] [--render-only]

Population: the 144 extended personas (8 archetypes x 3 calibrations x 6 replicates, truth rows, fine evidence), labels archetype and
calibration. Levels: raw rows summarised per persona (`ceiling.raw_features`; also without age), the full per-slice channel levels
the image encodes (`ceiling.level_features`; also with the fine ring), and the pre-registered summary features (the battery's).
Classifiers: nearest centroid (the battery's) and L2 multinomial logistic regression with the penalty chosen by nested
cross-validation inside every leave-one-out training fold. Writes `<out>.json` (every number) and `<out>.md`; the predictions below
are fixed in this file before the first measurement. No language or image model is run: the personas are generated by the
deterministic generator and the classifiers are fitted on its output. `--render-only` rebuilds the markdown from the json (with
`--reading`, the author-of-the-run's interpretation appended verbatim).
"""
