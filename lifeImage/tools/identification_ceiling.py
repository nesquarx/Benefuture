# ---------- build ----------

def build():
    ext = ch.extended_population()
    rows, asof = {}, {}
    for e in ext:
        rows[e["id"]], asof[e["id"]] = ch.extended_rows(e)
    cards = ch.world_cards()
    fine_cards = [c for c in cards if c.get("level") == "fine"]
    recs, states = ch.population_records(ext, rows, asof)
    out = {}
    out["raw"] = ce.raw_features(ext, rows, asof, fine_cards)
    out["raw_noage"] = ce.drop_columns(*out["raw"], set(ce.AGE_FEATURES))
    out["levels"] = ce.level_features(states)
    out["levels_fine"] = ce.level_features(states, fine=True)
    sn = ch.identification_names(recs)
    out["summary"] = (sn, ce.summary_features(recs, sn))
    y = {lab: [r[lab] for r in recs] for lab in LABELS}
    return out, y


_DATA = {}


def _job(key):
    level, label, clf = key
    X, y = _DATA["X"][level][1], _DATA["y"][label]
    if clf == "centroid":
        return key, ce.centroid_loo(X, y), None
    preds, cs = ce.logistic_loo(X, y)
    return key, preds, cs


def run():
    X, y = build()
    _DATA.update(X=X, y=y)
    jobs = [(lv, lab, c) for lv in LEVELS for lab in LABELS for c in CLFS]
    jobs.sort(key=lambda k: k[2] == "logistic", reverse=True)
    with Pool(min(4, os.cpu_count() or 1)) as pool:
        res = dict((k, (p, cs)) for k, p, cs in pool.imap_unordered(_job, jobs))
    out = {"n": len(y["archetype"]), "columns": {lv: len(X[lv][0]) for lv in LEVELS}, "labels": {lab: y[lab] for lab in LABELS}, "results": {}}
    for (lv, lab, c), (preds, cs) in sorted(res.items()):
        cl = CLASSES[lab]
        m = ce.confusion(y[lab], preds, cl)
        entry = {**ce.accuracy(y[lab], preds), "confusion": m, "recalls": ce.recalls(m, cl), "top_confusions": ce.top_confusions(m, cl, 6),
                 "predictions": preds}
        if cs:
            entry["chosen_c"] = {str(k): cs.count(k) for k in ce.C_GRID}
        out["results"].setdefault(lv, {}).setdefault(lab, {})[c] = entry
    out["paired"] = paired_table(out)
    out["verdicts"] = [verdict(p, out) for p in PREDICTIONS]
    return out


# ---------- comparisons and verdicts ----------

def flags(out, label, a):
    return [p == t for p, t in zip(out["results"][a[0]][label][a[1]]["predictions"], out["labels"][label])]


def paired(fa, fb):
    n = len(fa)
    x = sum(1 for p, q in zip(fa, fb) if p and not q)
    y = sum(1 for p, q in zip(fa, fb) if q and not p)
    d = (x - y) / n
    se = math.sqrt(max(0.0, (x + y) - (x - y) ** 2 / n)) / n
    _, _, p = ce.sign_test(fa, fb)
    return {"diff": d, "lo": d - 1.96 * se, "hi": d + 1.96 * se, "only_a": x, "only_b": y, "sign_p": p}


PAIRS = [(("raw", "logistic"), ("summary", "logistic")), (("levels", "logistic"), ("summary", "logistic")),
         (("raw", "logistic"), ("levels", "logistic")), (("levels_fine", "logistic"), ("levels", "logistic")),
         (("raw", "logistic"), ("raw", "centroid")), (("levels", "logistic"), ("levels", "centroid")),
         (("summary", "logistic"), ("summary", "centroid")), (("raw_noage", "logistic"), ("raw", "logistic"))]


def paired_table(out):
    return [{"label": lab, "a": list(a), "b": list(b), **paired(flags(out, lab, a), flags(out, lab, b))} for lab in LABELS for a, b in PAIRS]


def verdict(p, out):
    lab, k = p["label"], p["kind"]
    base = {"id": p["id"], "label": lab, "kind": k, "conf": p["conf"], "text": p["text"]}
    if k in ("min", "max"):
        r = out["results"][p["a"][0]][lab][p["a"][1]]
        return {**base, **ch.identification_verdict(k, p["value"], r["correct"], r["n"])}
    if k in ("diff", "equiv"):
        r = paired(flags(out, lab, p["a"]), flags(out, lab, p["b"]))
        d = p["delta"]
        if k == "diff":
            v = "held" if r["diff"] >= d and r["lo"] > 0 else "not held" if r["hi"] < d else "inconclusive"
        else:
            v = "held" if r["lo"] > -d and r["hi"] < d else "not held" if r["lo"] > d or r["hi"] < -d else "inconclusive"
        return {**base, **r, "delta": d, "verdict": v}
    r = out["results"][p["a"][0]][lab][p["a"][1]]
    if k == "rank_pair":
        top = [(a, b) for a, b, _, _ in r["top_confusions"][:p["top"]]]
        got = tuple(sorted(p["pair"])) in [tuple(sorted(t)) for t in top]
        return {**base, "verdict": "held" if got else "not held", "observed": [list(t) for t in top]}
    order = sorted(r["recalls"], key=lambda c: (r["recalls"][c], c))
    order = order if k == "rank_low" else order[::-1]
    got = [c for c in order[:p["k"]]]
    ok = bool(set(got) & set(p["classes"])) if k == "rank_low" else set(got) == set(p["classes"])
    return {**base, "verdict": "held" if ok else "not held", "observed": got}


# ---------- report ----------

def f3(x):
    return f"{x:.3f}"


def iv(r):
    return f"{r['accuracy']:.3f} [{r['wilson'][0]:.3f}, {r['wilson'][1]:.3f}]"


def matrix_md(m, classes):
    short = [c[:4] for c in classes]
    L = ["| truth \\ predicted | " + " | ".join(short) + " | recall |", "|---|" + "---|" * (len(classes) + 1)]
    for i, c in enumerate(classes):
        n = sum(m[i])
        L.append(f"| {c} | " + " | ".join(str(v) if j != i else f"**{v}**" for j, v in enumerate(m[i])) + f" | {m[i][i] / n:.2f} |")
    return L


def pred_text(p):
    if p["kind"] in ("min", "max"):
        return f"{p['a'][0]} / {p['a'][1]}: {'at least' if p['kind'] == 'min' else 'at most'} {p['value']:.2f}"
    if p["kind"] == "diff":
        return f"{p['a'][0]}/{p['a'][1]} minus {p['b'][0]}/{p['b'][1]} at least {p['delta']:.2f}"
    if p["kind"] == "equiv":
        return f"{p['a'][0]}/{p['a'][1]} and {p['b'][0]}/{p['b'][1]} within {p['delta']:.2f}"
    return f"{p['a'][0]}/{p['a'][1]}: {p['kind'].replace('_', ' ')}"


