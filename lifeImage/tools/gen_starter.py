#!/usr/bin/env python3
"""Generate the starter set into data/synthetic/: 40 synthetic personas (spread over archetypes, ages 8-85) and 6
organisations, with rows, ground-truth events, texts for extraction tests and a summary table.

    python3 tools/gen_starter.py          # writes data/synthetic/ (deterministic: reruns are byte-identical)
    python3 tools/gen_starter.py --check  # regenerates in memory and compares with what is on disk

Everything here is synthetic (LI.15): no real person, no real minor.
"""
import argparse
import gzip
import hashlib
import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from lifeimage.generators import life, org  # noqa: E402
from lifeimage.generators.common import validate_row  # noqa: E402
from lifeimage.generators.params import ARCHETYPES  # noqa: E402

OUT = ROOT / "data" / "synthetic"
AS_OF = "2026-11-24"
PERSONAS = [  # (archetype, ages); five of each archetype, ages 8-85 overall
    ("student", [8, 11, 15, 19, 23]), ("shift_worker", [24, 33, 41, 52, 61]), ("carer", [29, 38, 47, 58, 71]),
    ("small_business_owner", [30, 39, 46, 55, 67]), ("researcher", [26, 34, 43, 56, 69]), ("retiree", [64, 70, 75, 80, 85]),
    ("career_changer", [29, 35, 42, 50, 59]), ("generalist", [18, 34, 48, 60, 78]),
]
ORGS = [("cafe", 2001), ("charity", 2002), ("software_firm", 2003), ("farm", 2004), ("clinic", 2005), ("sports_club", 2006)]


def gz(text):
    """Deterministic gzip (no timestamp), so regenerated files are byte-identical."""
    import io
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", mtime=0, compresslevel=9) as f:
        f.write(text.encode("utf-8"))
    return buf.getvalue()


def jl(rows):
    return "".join(json.dumps(r, sort_keys=True, ensure_ascii=False, separators=(",", ":")) + "\n" for r in rows)


def build():
    """{relative path: text} of everything the starter set holds."""
    files, personas, orgs = {}, [], []
    n = 0
    for arch, ages in PERSONAS:
        for age in ages:
            n += 1
            personas.append(life.generate_persona(1000 + n, arch, age, as_of=AS_OF, pid=f"p{n:03d}"))
    for kind, seed in ORGS:
        orgs.append(org.generate_org(seed, kind, as_of=AS_OF, oid=f"o{seed - 2000:03d}"))
    for r in [r for p in personas for r in p.rows] + [r for o in orgs for r in o.rows]:
        validate_row(r)
    files["personas.jsonl"] = jl([p.meta() for p in personas])
    files["rows.jsonl"] = jl([r for p in personas for r in p.rows])
    files["events.jsonl.gz"] = gz(jl([{"entity": p.entity, **{k: v for k, v in e.items()}} for p in personas for e in p.events if e["rows"]]))
    files["orgs.jsonl"] = jl([o.meta() for o in orgs])
    files["org_rows.jsonl"] = jl([r for o in orgs for r in o.rows])
    files["org_events.jsonl.gz"] = gz(jl([{"entity": o.entity, **e} for o in orgs for e in o.events if e["rows"]]))
    for p in personas:
        for kind, text in p.texts.items():
            files[f"texts/{p.id}.{kind}.txt"] = text
        files[f"truth/{p.id}.jsonl"] = jl(p.truth_rows)
    for o in orgs:
        files[f"texts/{o.id}.prospectus.txt"] = o.text
        files[f"truth/{o.id}.jsonl"] = jl(o.truth_rows)
    files["SUMMARY.md"] = summary(personas, orgs, files)
    files["manifest.json"] = json.dumps({
        "as_of": AS_OF, "generator_versions": {"life": life.GENERATOR_VERSION, "org": org.GENERATOR_VERSION},
        "personas": len(personas), "organisations": len(orgs), "synthetic": True,
        "sha256": {k: hashlib.sha256(v if isinstance(v, bytes) else v.encode()).hexdigest() for k, v in sorted(files.items()) if k.endswith((".jsonl", ".gz"))}}, indent=1, sort_keys=True) + "\n"
    return files


def est_error(p):
    errs = []
    for r in p.rows:
        if r["channel"] != "prediction":
            continue
        kind = "impact" if any(m["rel"] == "outcome" for m in r["memberships"]) else "expertise"
        errs.append(r["magnitude"] - p.latent[r["memberships"][0]["domain"]][kind])
    return st.mean(errs) if errs else None


def fmt_err(e):
    return "n/a" if e is None else f"{e:+.3f}"


def tiers(rows):
    return [sum(r["tier"] == t for r in rows) for t in ("claimed", "attested", "measured")]


def summary(personas, orgs, files):
    L = ["# Synthetic starter set", "",
         f"Generated by `tools/gen_starter.py` (as of {AS_OF}); every entity is synthetic (LI.15). {len(personas)} personas, {len(orgs)} organisations. "
         "Rows follow the evidence contract (A3S membership types form, content, outcome, setting; channels positive, prediction for self-assessed "
         "potential, negative for rare harm). Per entity: rows by channel, rows by tier (claimed / attested / measured), distinct domains touched, "
         "and the calibration of the self-assessment (mean of estimate minus latent truth over the potential rows).", "",
         "## Personas", "", "| id | archetype | age | rows | positive | prediction | negative | claimed | attested | measured | domains | events recorded / latent | calibration | mean estimate error |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for p in personas:
        ch = {c: sum(r["channel"] == c for r in p.rows) for c in ("positive", "prediction", "negative")}
        c, a, m = tiers(p.rows)
        doms = len({m_["domain"] for r in p.rows for m_ in r["memberships"]})
        rec = sum(1 for e in p.events if e["rows"])
        L.append(f"| {p.id} | {p.archetype} | {p.age} | {len(p.rows)} | {ch['positive']} | {ch['prediction']} | {ch['negative']} | {c} | {a} | {m} | {doms} | {rec} / {len(p.events)} | {p.calibration} | {fmt_err(est_error(p))} |")
    allp = [r for p in personas for r in p.rows]
    c, a, m = tiers(allp)
    tot = len(allp)
    L += ["", f"Totals: {tot} rows; tiers claimed {c} ({c / tot:.0%}), attested {a} ({a / tot:.0%}), measured {m} ({m / tot:.0%}); "
          f"channels positive {sum(r['channel'] == 'positive' for r in allp)}, prediction {sum(r['channel'] == 'prediction' for r in allp)}, "
          f"negative {sum(r['channel'] == 'negative' for r in allp)}.", ""]
    for cal in ("over", "under", "well"):
        errs = [e for e in (est_error(p) for p in personas if p.calibration == cal) if e is not None]
        if errs:
            L.append(f"- calibration `{cal}`: {len(errs)} personas, mean estimate error {st.mean(errs):+.3f} (persona range {min(errs):+.3f} to {max(errs):+.3f})")
    L += ["", "## Organisations", "", "| id | kind | name | founded | rows | positive | negative | claimed | attested | measured | domains |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for o in orgs:
        c, a, m = tiers(o.rows)
        doms = len({m_["domain"] for r in o.rows for m_ in r["memberships"]})
        L.append(f"| {o.id} | {o.kind} | {o.name} | {o.founded} | {len(o.rows)} | {sum(r['channel'] == 'positive' for r in o.rows)} | {sum(r['channel'] == 'negative' for r in o.rows)} | {c} | {a} | {m} | {doms} |")
    L += ["", "## Files", "",
          "- `personas.jsonl`, `orgs.jsonl`: entity metadata (id, seed, archetype or kind, age or founding, calibration and bias, latent potential per domain, fictional contact details).",
          "- `rows.jsonl`, `org_rows.jsonl`: contract rows; `provenance.source` is `<document or record>:<entity id>`, `span` is `L<line>` into the text (claimed) or `ev:<event id>` (attested, measured).",
          "- `events.jsonl.gz`, `org_events.jsonl.gz` (gzip, JSON lines): ground-truth events that left at least one row, with their participation records (persons), row indices into the entity's rows in file order, and the phrase a claimed row came from.",
          "- `texts/<id>.{resume,self,diary}.txt`, `texts/<id>.prospectus.txt`: texts for extraction tests; `truth/<id>.jsonl`: the claimed rows an extractor should recover from them.",
          "- `manifest.json`: hashes; `python3 tools/gen_starter.py --check` regenerates and compares.", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = build()
    if args.check:
        bad = [k for k, v in files.items() if not (OUT / k).exists() or (OUT / k).read_bytes() != (v if isinstance(v, bytes) else v.encode("utf-8"))]
        print("starter set matches" if not bad else f"MISMATCH: {bad[:5]}")
        return 1 if bad else 0
    for k, v in files.items():
        f = OUT / k
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_bytes(v if isinstance(v, bytes) else v.encode("utf-8"))
    print(f"wrote {len(files)} files, {sum(len(v) for v in files.values()) / 1e6:.1f} MB to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
